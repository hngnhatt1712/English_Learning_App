"""Build Owla's Android vectors from the untouched layered SVG (stdlib only).

Run from any directory: python icon/generate_owla_vectors.py
The six transparent eyelid paths reuse the source eye contours/shadows. Compose
controls their clip groups; SVG IDs alone do not provide animatable layers.
"""

from copy import deepcopy
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SVG = "http://www.w3.org/2000/svg"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)
SOURCE = ROOT / "icon/owla_layered.svg"
DRAWABLE = ROOT / "app/src/main/res/drawable"
HEAD_VIEWBOX = "0 0 1197 760"
HEAD_IDS = {
    "glasses", "head_tufts", "eye_white_left", "eye_shadow_left",
    "face_disc", "eye_left_look", "beak", "beak_bridge", "beak_tip",
    "eye_white_right", "eye_shadow_right", "eye_right_look",
}


def attrs(**values):
    return {f"{{{ANDROID}}}{key}": str(value) for key, value in values.items()}


def convert(node, animated=False):
    kind = node.tag.removeprefix(f"{{{SVG}}}")
    if kind == "g":
        result = ET.Element("group", attrs(name=node.attrib["id"]))
        for child in node:
            result.append(convert(child, animated))
        return result
    assert kind == "path", f"Unsupported SVG element: {kind}"
    assert set(node.attrib) <= {"id", "fill", "fill-rule", "clip-rule", "d"}
    assert node.get("fill-rule") == node.get("clip-rule") == "evenodd"
    path = ET.Element("path", attrs(
        name=node.attrib["id"], fillColor=node.attrib["fill"],
        fillType="evenOdd", pathData=node.attrib["d"],
    ))
    if animated and node.attrib["id"].startswith("pupil_"):
        group = ET.Element("group", attrs(name=f'{node.attrib["id"]}_motion'))
        group.append(path)
        return group
    return path


def write_vector(nodes, path, height, animated=False):
    vector = ET.Element("vector", attrs(
        width="96dp" if animated else "48dp",
        height=f"{96 * height / 1197:.6f}dp" if animated else f"{48 * height / 1197:.6f}dp",
        viewportWidth=1197, viewportHeight=height,
    ))
    by_id = {node.get("id"): node for node in nodes}
    for node in nodes:
        item = convert(node, animated)
        name = node.get("id", "")
        if animated and (name.startswith("wing_") or name == "head_tufts"):
            group = ET.SubElement(vector, "group", attrs(name=f"{name}_motion"))
            group.append(item)
        else:
            vector.append(item)
        if animated and name in {"eye_left_look", "eye_right_look"}:
            side = name.split("_")[1]
            white = by_id[f"eye_white_{side}"]
            # The first closed contour is the outside of the eye; the later
            # relative moveto begins the even-odd hole containing iris/pupil.
            outer = re.split(r"m(?=[-\d.])", white.attrib["d"], maxsplit=1)[0]
            for lid in ("top", "bottom"):
                group = ET.SubElement(vector, "group", attrs(name=f"lid_{side}_{lid}"))
                # Compose parses clip-path as its own nested VectorGroup. Name
                # that clip explicitly so runtime configs target the actual clip.
                ET.SubElement(group, "clip-path", attrs(
                    name=f"lid_{side}_{lid}_clip", pathData="M0,0h0v0z",
                ))
                ET.SubElement(group, "path", attrs(
                    name=f"lid_{side}_{lid}_fill", pathData=outer,
                    fillColor=white.attrib["fill"], fillType="evenOdd", fillAlpha=0,
                ))
            group = ET.SubElement(vector, "group", attrs(name=f"lid_{side}_crease"))
            shadow = by_id[f"eye_shadow_{side}"]
            crease = convert(shadow)
            crease.set(f"{{{ANDROID}}}name", f"lid_{side}_crease_fill")
            crease.set(f"{{{ANDROID}}}fillAlpha", "0")
            group.append(crease)
    ET.indent(vector, space="    ")
    path.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by icon/generate_owla_vectors.py; edit the generator, not this file. -->\n'
        + ET.tostring(vector, encoding="unicode") + "\n", encoding="utf-8",
    )


def main():
    source = ET.parse(SOURCE).getroot()
    assert source.attrib["viewBox"] == "0 0 1197 1519"
    nodes = [node for node in source if node.tag != f"{{{SVG}}}metadata"]
    assert len(list(source.iter(f"{{{SVG}}}path"))) == 30
    write_vector(nodes, DRAWABLE / "owla_mascot.xml", 1519, animated=True)
    # A crop alone would retain the shoulders/body at y~580-760. Explicitly
    # exclude both wings, body, belly, feet, feathers and tail from this asset.
    head_nodes = [node for node in nodes if node.get("id") in HEAD_IDS]
    head = ET.Element(f"{{{SVG}}}svg", {
        "width": "1197", "height": "760", "fill": "none", "viewBox": HEAD_VIEWBOX,
    })
    for node in head_nodes:
        head.append(deepcopy(node))
    ET.register_namespace("", SVG)
    ET.indent(head, space="  ")
    (ROOT / "icon/owla_head.svg").write_text(
        ET.tostring(head, encoding="unicode") + "\n", encoding="utf-8",
    )
    write_vector(head_nodes, DRAWABLE / "owla_head.xml", 760)


if __name__ == "__main__":
    main()
